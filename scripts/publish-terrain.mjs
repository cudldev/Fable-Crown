// Build a static byte-exact cache; editable VOX source files are never rewritten here.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { terrainVersion, validateTerrainPack } from './check-terrain-assets.mjs';

const source = 'assets/source/voxel/terrain-style-a-v3', output = 'public/art3d/terrain';
const original = JSON.parse(await readFile(source + '/manifest.json', 'utf8'));
if (!Array.isArray(original.assets) || !original.assets.length) throw Error('Missing editable terrain sources');
const inputs = await Promise.all(original.assets.map(async asset => {
  if (!/^[a-z0-9-]+$/.test(asset.id) || asset.file !== asset.id + '.vox') throw Error('Nonlocal terrain source');
  return { asset, raw: await readFile(source + '/' + asset.file) };
}));
const sourceHash = createHash('sha256'); let offset = 0;
const assets = inputs.map(({ asset, raw }) => {
  sourceHash.update(asset.file).update(raw);
  const result = { ...asset, byteOffset: offset, byteLength: raw.length }; offset += raw.length; return result;
});
const sourceVersion = sourceHash.digest('hex').slice(0, 16);
if (original.version !== sourceVersion) throw Error('Editable terrain metadata is stale; run node tools/voxel-terrain/check-kit.mjs terrain-style-a-v3 --write');
const pack = Buffer.concat(inputs.map(input => input.raw));
const manifest = { ...original, status: 'Published immutable native VOX cache; authored source files remain the editing source of truth', source, sourceVersion,
  pack: 'tiles.bin', files: ['art3d/terrain/tiles.bin'], bytes: pack.length, packSha256: createHash('sha256').update(pack).digest('hex'), assets };
manifest.version = terrainVersion(manifest, pack);
const result = validateTerrainPack(manifest, pack), text = JSON.stringify(manifest, null, 2) + '\n';
const versionSource = '// Generated by scripts/publish-terrain.mjs. Version both delivery URLs to avoid mixed PWA caches.\nexport const TERRAIN_VERSION = ' + JSON.stringify(manifest.version) + ';\n';
if (process.argv.includes('--check')) {
  const [savedManifest, savedPack] = await Promise.all([readFile(output + '/manifest.json', 'utf8'), readFile(output + '/tiles.bin')]);
  if (savedManifest.replace(/\r\n/g, '\n') !== text || !savedPack.equals(pack)) throw Error('Terrain publication differs from current editable source');
  if ((await readFile('src/render/three/terrain-version.ts', 'utf8')).replace(/\r\n/g, '\n') !== versionSource) throw Error('Terrain runtime version is stale');
} else {
  await mkdir(output, { recursive: true });
  await Promise.all([writeFile(output + '/manifest.json', text), writeFile(output + '/tiles.bin', pack), writeFile('src/render/three/terrain-version.ts', versionSource)]);
}
console.log(`Native terrain ${process.argv.includes('--check') ? 'matches source' : 'published'}: ${result.modules} modules, ${result.bytes} bytes, ${result.version}`);
