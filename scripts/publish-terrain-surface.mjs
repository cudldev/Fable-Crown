// Compile reusable terrain pigment once; world-specific arrangement remains a runtime operation.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createServer } from 'vite';

const output = 'public/art3d/terrain';
const nativeManifest = JSON.parse(await readFile(output + '/manifest.json', 'utf8'));
const nativePack = await readFile(output + '/tiles.bin');
const server = await createServer({ configFile: false, appType: 'custom', optimizeDeps: { noDiscovery: true, include: [] },
  server: { middlewareMode: true, watch: null, hmr: false, ws: false }, logLevel: 'error' });
try {
  const { parseTerrainTiles, compileTerrainTiles, parseCompiledTerrain } = await server.ssrLoadModule('/src/render/three/terrain-tiles.ts');
  const native = parseTerrainTiles(nativeManifest, nativePack.buffer.slice(nativePack.byteOffset, nativePack.byteOffset + nativePack.byteLength));
  const { metadata, pack } = compileTerrainTiles(native), bytes = Buffer.from(pack);
  // Do not include generated version sources in their own hash. Include algorithm sources even
  // when a particular source change happens to leave this asset's output unchanged.
  const hash = createHash('sha256').update('fable-terrain-surface-v1\0');
  for (const file of ['scripts/publish-terrain-surface.mjs', 'src/render/three/terrain-tiles.ts', 'src/render/three/voxel-data.ts'])
    hash.update(file).update((await readFile(file, 'utf8')).replace(/\r\n/g, '\n'));
  hash.update(JSON.stringify(nativeManifest)).update(nativePack).update(JSON.stringify(metadata)).update(bytes);
  const version = hash.digest('hex').slice(0, 16);
  const manifest = { ...metadata, version, packSha256: createHash('sha256').update(bytes).digest('hex') };
  parseCompiledTerrain(manifest, pack, version, nativeManifest.version);
  const text = JSON.stringify(manifest, null, 2) + '\n';
  const versionSource = '// Generated by scripts/publish-terrain-surface.mjs. Version compiled runtime delivery independently of native VOX.\nexport const TERRAIN_SURFACE_VERSION = ' + JSON.stringify(version) + ';\n';
  const generated = 'src/render/three/terrain-surface-version.ts';
  if (process.argv.includes('--check')) {
    const [savedManifest, savedPack, savedVersion] = await Promise.all([readFile(output + '/surface.json', 'utf8'), readFile(output + '/surface.bin'), readFile(generated, 'utf8')]);
    if (savedManifest.replace(/\r\n/g, '\n') !== text || !savedPack.equals(bytes) || savedVersion.replace(/\r\n/g, '\n') !== versionSource) throw Error('Compiled terrain surface is stale; run node scripts/publish-terrain-surface.mjs');
  } else {
    await mkdir(output, { recursive: true });
    await Promise.all([writeFile(output + '/surface.json', text), writeFile(output + '/surface.bin', bytes), writeFile(generated, versionSource)]);
  }
  console.log(`Compiled terrain ${process.argv.includes('--check') ? 'verified' : 'published'}: ${metadata.assets.length} modules; ${bytes.length} bytes; ${version}`);
} finally { await server.close(); }
