// Reuse the exact TypeScript compiler in Node; no VOX preparation ships in the game.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { gzipSync } from 'node:zlib';
import { createRequire } from 'node:module';
import { createServer } from 'vite';

const output = 'public/art3d/voxel';
const native = JSON.parse(await readFile(output + '/manifest.json', 'utf8'));
const compilerFiles = ['scripts/bake-voxel-assets.mjs', 'src/render/three/voxel-bake-source.ts', 'src/render/three/voxel-bake.ts',
  'src/render/three/voxel-decode.ts', 'src/render/three/voxel-data.ts', 'src/render/three/voxel-surface.ts', 'src/render/three/voxel-assets.ts'];
const hash = createHash('sha256').update(native.version).update(JSON.stringify(native.assets));
for (const file of compilerFiles) hash.update(file).update((await readFile(file, 'utf8')).replace(/\r\n/g, '\n'));
hash.update(await readFile(createRequire(import.meta.url).resolve('three')));
const server = await createServer({ configFile: false, appType: 'custom', logLevel: 'error', server: { middlewareMode: true, watch: null, ws: false }, optimizeDeps: { noDiscovery: true, include: [] } });
try {
  const { voxelAssetSpecs } = await server.ssrLoadModule('/src/render/three/voxel-assets.ts');
  const { bakeVoxelAssets } = await server.ssrLoadModule('/src/render/three/voxel-bake-source.ts');
  const { encodeVoxelBake, decodeVoxelBake } = await server.ssrLoadModule('/src/render/three/voxel-bake.ts');
  const specs = voxelAssetSpecs(native), inputs = [];
  for (const spec of specs) {
    const raw = await readFile(output + '/' + spec.file); hash.update(spec.file).update(raw);
    inputs.push({ spec, buffer: Uint8Array.from(raw).buffer });
  }
  const compiled = bakeVoxelAssets(native.version, inputs), binary = encodeVoxelBake(compiled);
  decodeVoxelBake(binary, native.version); // Validate before publishing a partial/broken package.
  const pack = gzipSync(new Uint8Array(binary), { level: 9 });
  pack[9] = 255; // Portable gzip OS marker; Windows/Linux publish identical headers.
  if (binary.byteLength > 64 * 1024 * 1024 || pack.length > 16 * 1024 * 1024) throw Error('Voxel bake exceeds the runtime package budget.');
  const version = hash.update(pack).digest('hex').slice(0, 16);
  // Compression belongs to the application; a .gz suffix makes some static
  // servers transparently decode it, changing the bytes/hash seen by fetch().
  const manifest = { format: 1, version, sourceVersion: native.version, pack: 'meshes.bin', encoding: 'gzip', bytes: pack.length,
    decodedBytes: binary.byteLength, packSha256: createHash('sha256').update(pack).digest('hex'),
    assets: compiled.assets.map(asset => ({ id: asset.id, size: asset.size })),
    files: ['art3d/voxel/meshes.bin'] };
  const text = JSON.stringify(manifest, null, 2) + '\n';
  const versionSource = '// Generated by scripts/bake-voxel-assets.mjs. Includes native bytes and compiler inputs.\nexport const VOXEL_BAKE_VERSION = ' + JSON.stringify(version) + ';\n';
  const files = [[output + '/baked.json', text], [output + '/meshes.bin', pack], ['src/render/three/voxel-bake-version.ts', versionSource]];
  if (process.argv.includes('--check')) {
    for (const [file, value] of files) {
      const saved = await readFile(file);
      if (typeof value === 'string' ? saved.toString().replace(/\r\n/g, '\n') !== value : !saved.equals(value)) throw Error('Stale voxel bake: ' + file);
    }
  } else {
    await mkdir(output, { recursive: true });
    for (const [file, value] of files) await writeFile(file, value);
  }
  console.log(`Voxel bake ${process.argv.includes('--check') ? 'verified' : 'published'}: ${compiled.assets.length} bindings, ${binary.byteLength} raw / ${pack.length} gzip bytes, ${version}`);
} finally { await server.close(); }
