import { expect, test } from "@playwright/test";
import { renderFrameCount } from "./render-profile";
import { mkdir, writeFile } from "node:fs/promises";
import { createRpg } from "../src/rpg/engine";
import { DEFAULT_VISUAL_SETTINGS } from "../src/render/three/visual-settings";

test("visual controls update the renderer, copy a reusable preset, reset and fit on mobile", async ({ page, context, baseURL }) => {
  await context.grantPermissions(["clipboard-read", "clipboard-write"], { origin: new URL(baseURL!).origin });
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
  await page.setViewportSize({ width: 1280, height: 800 }); await page.goto("./?renderer=3d");
  const world = page.getByTestId("rpg-world"); await expect(world).toHaveAttribute("data-status", "ready", { timeout: 45000 });
  const fixture = createRpg(Date.now(), 8128);
  Object.assign(fixture.control, { waiting: true, goal: null, active: null, source: null, queue: [], thought: null, thinkingUntil: 1_000_000_000 }); fixture.player.path = [];
  await page.getByRole("button", { name: "Open game menu" }).click();
  await page.locator('input[type="file"]').setInputFiles({ name: "visual-fixture.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(fixture)) });
  await expect(page.getByRole("status")).toContainText("Chronicle restored"); await page.getByRole("button", { name: "Close panel" }).click();
  await page.getByRole("button", { name: "Dusk lighting", exact: true }).click();
  await page.getByRole("button", { name: "Orthographic camera" }).click();
  await page.getByRole("button", { name: "Visual settings", exact: true }).click();
  const panel = page.getByRole("dialog", { name: "Visual settings" }); await expect(panel).toBeVisible();
  await expect(panel.locator("[data-visual-performance]")).toContainText("FPS");
  const output = "docs/art-audit/visual-controls-v1"; await mkdir(output, { recursive: true });
  await page.evaluate(async count => { for (let i = 0; i < count; i++) await new Promise(resolve => requestAnimationFrame(resolve)); }, renderFrameCount(120));
  await page.screenshot({ path: output + "/desktop.png" });
  const position = [await world.getAttribute("data-camera-x"), await world.getAttribute("data-camera-y")];
  await panel.getByRole("slider", { name: "Exposure", exact: true }).press("End");
  await expect(world).toHaveAttribute("data-exposure", "2.00");
  await panel.getByRole("slider", { name: "Sun brightness", exact: true }).press("End");
  await expect(world).toHaveAttribute("data-sun-power", "5.100");
  await panel.getByRole("combobox", { name: "Shadow resolution" }).selectOption("2048");
  await expect(world).toHaveAttribute("data-shadow-map-size", "2048");
  await panel.getByRole("checkbox", { name: "Enable sun shadows" }).uncheck();
  await expect(world).toHaveAttribute("data-shadow-lights", "0");
  await panel.getByRole("slider", { name: "Bounced light strength" }).press("Home");
  await panel.getByRole("slider", { name: "Occlusion strength" }).press("Home");
  await panel.getByRole("slider", { name: "AO distance", exact: true }).press("Home");
  await expect(panel.getByRole("slider", { name: "AO distance", exact: true })).toHaveValue("0.125");
  await expect(panel.locator(".visual-slider").filter({ hasText: "AO distance" })).toContainText("0.125 m");
  await panel.getByRole("slider", { name: "AO distance", exact: true }).press("ArrowRight");
  await expect(panel.getByRole("slider", { name: "AO distance", exact: true })).toHaveValue("0.25");
  await panel.getByRole("slider", { name: "AO distance", exact: true }).press("Home");
  await panel.getByRole("checkbox", { name: "Enable fog" }).uncheck(); await expect(world).toHaveAttribute("data-fog-active", "false");
  expect([await world.getAttribute("data-camera-x"), await world.getAttribute("data-camera-y")]).toEqual(position);
  await panel.getByRole("button", { name: "Copy settings", exact: true }).click();
  await expect(panel.getByRole("button", { name: "Copy settings", exact: true })).toHaveText("Copied!");
  const copied = await page.evaluate(() => navigator.clipboard.readText()), preset = JSON.parse(copied);
  expect(preset.type).toBe("fable-crown.visual-settings"); expect(preset.version).toBe(1); expect(preset.cameraMode).toBe("orthographic");
  expect(preset.shadows).toBe(false); expect(preset.visual).toMatchObject({ exposure: 2, sunStrength: 3, shadowResolution: 2048, giStrength: 0, aoStrength: 0, aoDistance: .125, fogEnabled: false });
  await writeFile(output + "/copied-preset.json", copied + "\n");
  await panel.getByRole("button", { name: "Copy performance", exact: true }).click();
  await expect(panel.getByRole("button", { name: "Copy performance", exact: true })).toHaveText("Copied!");
  const diagnostic = JSON.parse(await page.evaluate(() => navigator.clipboard.readText()));
  expect(diagnostic.type).toBe("fable-crown.performance"); expect(diagnostic.counters.terrainSource).toBe("vox");
  expect(diagnostic.counters.cpuRenderMs).toMatch(/^\d+\.\d+$/); expect(diagnostic).not.toHaveProperty("state");
  await panel.getByRole("button", { name: "Reset visual settings" }).click();
  await expect.poll(async () => JSON.parse((await world.getAttribute("data-visual-settings"))!)).toEqual({ ...DEFAULT_VISUAL_SETTINGS,
    sunAzimuth: expect.closeTo(DEFAULT_VISUAL_SETTINGS.sunAzimuth, 10), sunElevation: expect.closeTo(DEFAULT_VISUAL_SETTINGS.sunElevation, 10) });
  await expect(world).toHaveAttribute("data-lighting", "dusk"); await expect(world).toHaveAttribute("data-camera-mode", "perspective");
  await panel.press("Escape"); await expect(panel).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Visual settings", exact: true })).toBeFocused();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Visual settings", exact: true }).click(); await expect(panel).toBeVisible();
  await page.screenshot({ path: output + "/phone.png" });
  const body = panel.locator(".visual-settings-body"), box = await body.boundingBox();
  await page.mouse.move(box!.x + box!.width / 2, box!.y + box!.height / 2); await page.mouse.wheel(0, 350);
  await expect.poll(() => body.evaluate(element => element.scrollTop)).toBeGreaterThan(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)).toBe(false);
  await page.setViewportSize({ width: 844, height: 390 }); await expect(panel).toBeVisible();
  expect(await body.evaluate(element => element.clientHeight)).toBeGreaterThan(100);
  await page.screenshot({ path: output + "/landscape.png" });
  expect(errors).toEqual([]);
});

test("copy settings offers selectable JSON when clipboard permission is denied", async ({ page }) => {
  await page.addInitScript(() => Object.defineProperty(navigator, "clipboard", { value: { writeText: async () => { throw Error("Clipboard denied for this test"); } }, configurable: true }));
  await page.goto("./?renderer=3d"); await expect(page.getByTestId("rpg-world")).toHaveAttribute("data-status", "ready", { timeout: 45000 });
  await page.getByRole("button", { name: "Visual settings", exact: true }).click();
  const panel = page.getByRole("dialog", { name: "Visual settings" }); await panel.getByRole("button", { name: "Copy settings", exact: true }).click();
  const text = panel.getByRole("textbox", { name: "Settings to copy" }); await expect(text).toBeVisible(); await expect(text).toBeFocused();
  expect(JSON.parse(await text.inputValue()).type).toBe("fable-crown.visual-settings");
  expect(await text.evaluate(element => (element as HTMLTextAreaElement).selectionEnd)).toBe((await text.inputValue()).length);
});
